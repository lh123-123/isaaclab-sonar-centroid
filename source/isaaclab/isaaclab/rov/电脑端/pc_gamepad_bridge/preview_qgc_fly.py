"""Offline Qt/QML rendering + HTTP/staleness checks; never connects to the ROV.

Run with the optional PySide6-Essentials test runtime on PYTHONPATH. Screenshots
are generated by this new QML view, not captured from the user's desktop.
"""
import argparse
import os
os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')
os.environ.setdefault('QT_QUICK_BACKEND', 'software')
import time
from pathlib import Path

from PySide6.QtCore import QObject, Property, QTimer, QUrl
from PySide6.QtGui import QFont, QFontDatabase, QGuiApplication
from PySide6.QtQml import qmlRegisterSingletonInstance
from PySide6.QtQuick import QQuickView

from qgc_fly_status import StatusServer


class Vehicle(QObject):
    @Property(int, constant=True)
    def id(self):
        return 1


class Manager(QObject):
    def __init__(self):
        super().__init__()
        self.vehicle = Vehicle()
    @Property(QObject, constant=True)
    def activeVehicle(self):
        return self.vehicle


class Qgc(QObject):
    def __init__(self):
        super().__init__()
        self.manager = Manager()
    @Property(QObject, constant=True)
    def multiVehicleManager(self):
        return self.manager


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, default=Path(__file__).with_name('qgc_fly_preview.png'))
    args = parser.parse_args()
    app = QGuiApplication([])
    font_id = QFontDatabase.addApplicationFont('C:/Windows/Fonts/msyh.ttc')
    QFontDatabase.addApplicationFont('C:/Windows/Fonts/msyhbd.ttc')
    if font_id < 0:
        raise RuntimeError('Preview requires the Windows Chinese UI font')
    app.setFont(QFont(QFontDatabase.applicationFontFamilies(font_id)[0]))
    fake = Qgc()
    qmlRegisterSingletonInstance(Qgc, 'QGroundControl', 1, 0, 'QGroundControl', fake)
    server = StatusServer(0)
    snapshot = {
        'schema': 1, 'target_system': 1, 'fc_online': True, 'armed': False,
        'depth_m': 1.23, 'descent_mps': -.01, 'depth_hold': True, 'attitude_hold': True,
        'roll_deg': -.9, 'pitch_deg': -7.9, 'heading_deg': 77,
        'gripper_next': '快速闭合', 'gripper_target_pwm': 900, 'gripper_output_pwm': 900,
        'motion_gain': .4, 'vertical_gain': .4, 'gimbal_target_deg': -20,
        'voltage_v': 24.1, 'current_a': 2.25, 'warning': '', 'hid_fresh': True,
        'sending': False, 'control_ready': False, 'allow_arm': False,
        'resources': {'temperature_c': 56, 'memory_percent': 14, 'pc_memory_percent': 68,
                      'tx_mbps': 2.6, 'link_percent': .26},
    }
    publish = QTimer()
    publish.timeout.connect(lambda: server.publish(snapshot, time.monotonic()))
    publish.start(100)
    server.publish(snapshot, time.monotonic())
    view = QQuickView()
    # Standalone Qt does not contain QGC's compiled native resource modules.
    # Render/test the actual pure card here; the native composite is verified
    # in the installed QGC app, never replaced with a mock compass.
    view.setSource(QUrl.fromLocalFile(str(Path(__file__).with_name('qgc') / 'ROVCompetitionCard.qml')))
    if view.status() == QQuickView.Error:
        raise RuntimeError('\n'.join(e.toString() for e in view.errors()))
    item = view.rootObject()
    item.setProperty('activeVehicleId', 1)
    item.setProperty('endpoint', f'http://127.0.0.1:{server.port}/status')
    view.resize(400, 180)
    view.show()
    errors = []
    def render():
        try:
            assert item.property('valid') and item.property('online'), 'XHR snapshot not available: ' + repr({
                key: item.property(key) for key in ('activeVehicleId', 'snapshot', 'receivedAt', 'clock', 'endpoint', 'valid')})
            assert item.findChild(QObject, 'depthLabel').property('text') == '1.23 m'
            assert item.findChild(QObject, 'gripperLabel').property('text') == 'RB 下次 闭合'
            assert item.findChild(QObject, 'depthHoldLabel').property('text') == 'X 定深 开'
            assert item.property('implicitHeight') < 150, 'normal card too large'
            view.resize(400, int(item.property('implicitHeight')))
            QTimer.singleShot(100, save)
        except Exception as error:
            errors.append(str(error))
            app.quit()
    def save():
        layout = item.findChild(QObject, 'contentLayout')
        assert layout.parentItem() is item, 'content must be visually parented to the card'
        assert layout.property('width') >= 380, 'layout clipped'
        rendered = view.grabWindow()
        assert len({rendered.pixelColor(x, y).rgba() for x in range(10, rendered.width(), 3)
                    for y in range(10, rendered.height(), 3)}) > 50, 'text did not render'
        if not rendered.save(str(args.output)):
            errors.append('render image save failed')
        # Different vehicle must not display another vehicle's values.
        item.setProperty('activeVehicleId', 2)
        assert not item.property('online')
        item.setProperty('activeVehicleId', 1)
        publish.stop()
        QTimer.singleShot(2400, verify_stale)
    def verify_stale():
        try:
            assert not item.property('valid'), 'stalled publisher remained current'
            assert item.findChild(QObject, 'depthLabel').property('text') == '—'
            assert '—' in item.findChild(QObject, 'gripperLabel').property('text')
        except Exception as error:
            errors.append(str(error))
        app.quit()
    QTimer.singleShot(1400, render)
    QTimer.singleShot(6000, app.quit)
    app.exec()
    server.close()
    if errors:
        raise RuntimeError('; '.join(errors))
    print('OFFLINE QML: render / XHR / vehicle identity / publisher timeout passed; fixture data only')
    print(args.output)


if __name__ == '__main__':
    main()
